async function readPrevious() {
  try {
    return JSON.parse(await fs.readFile(recordPath, "utf8"));
  } catch (error) {
    if (error.code === "ENOENT") return {};
    throw error;
  }
}

async function save(record) {
  await fs.mkdir(path.dirname(recordPath), { recursive: true });
  await fs.writeFile(recordPath, `${JSON.stringify(record, null, 2)}\n`);
}

async function uploadPicture(filePath) {
  const accessToken = await getAccessToken();
  const bytes = await fs.readFile(filePath);
  const form = new FormData();
  form.append("file", new Blob([bytes], { type: "image/jpeg" }), path.basename(filePath));
  const response = await fetch("https://api.mercadolibre.com/pictures/items/upload", {
    method: "POST",
    headers: { authorization: `Bearer ${accessToken}` },
    body: form
  });
  const raw = await response.text();
  const body = raw ? JSON.parse(raw) : {};
  if (!response.ok || !body.id) throw new Error(`Picture upload failed (${response.status}): ${JSON.stringify(body)}`);
  return body.id;
}

